import { writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { brandColors as c, brandMarkSvg, brandLogoSvg, brandLogoWidth, brandLogoHeight } from "../src/brand.js";

const root = fileURLToPath(new URL("../", import.meta.url));
const destination = path.join(root, "public/brand");
await mkdir(destination, { recursive: true });
const width = brandLogoWidth, height = brandLogoHeight;
const logoSvg = brandLogoSvg(), markSvg = brandMarkSvg(), faviconSvg = brandMarkSvg({ tile: true });
await Promise.all([
  writeFile(path.join(destination, "logo.svg"), logoSvg),
  writeFile(path.join(destination, "mark.svg"), markSvg),
  writeFile(path.join(root, "public/favicon.svg"), faviconSvg),
  writeFile(path.join(root, "web/brand.css"), `/* Generated by scripts/build-brand-assets.js. */\n:root {\n${Object.entries(c).map(([key,value]) => `  --brand-${key.replace(/[A-Z]/g, char => "-" + char.toLowerCase())}: ${value};`).join("\n")}\n}\n`),
]);

const browser = await chromium.launch({
  ...(process.env.SENDA_TEST_BROWSER ? { executablePath: process.env.SENDA_TEST_BROWSER } : {}),
  headless: true,
});
try {
  const page = await browser.newPage();
  async function png(svg, targetWidth, targetHeight, transparent = true) {
    await page.setViewportSize({ width: targetWidth, height: targetHeight });
    await page.setContent(`<html><body style="margin:0;background:${transparent ? "transparent" : "white"}"><img width="${targetWidth}" height="${targetHeight}" src="data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}"></body></html>`);
    await page.locator("img").evaluate(img => img.decode());
    return page.screenshot({ omitBackground: transparent });
  }
  const emailLogoWidth = 122, emailLogoHeight = 36;
  const emailPng = await png(logoSvg, emailLogoWidth * 2, emailLogoHeight * 2),
    emailDarkPng = await png(brandLogoSvg({ inverse: true }), emailLogoWidth * 2, emailLogoHeight * 2),
    faviconPng = await png(faviconSvg, 32, 32),
    touchPng = await png(faviconSvg, 180, 180),
    icon192 = await png(faviconSvg, 192, 192),
    oauthIcon = await png(faviconSvg, 120, 120),
    icon512 = await png(faviconSvg, 512, 512);
  await Promise.all([
    writeFile(path.join(destination, "email-logo.png"), emailPng),
    writeFile(path.join(destination, "email-logo-dark.png"), emailDarkPng),
    writeFile(path.join(root, "public/favicon-32.png"), faviconPng),
    writeFile(path.join(root, "public/apple-touch-icon.png"), touchPng),
    writeFile(path.join(destination, "icon-192.png"), icon192),
    writeFile(path.join(destination, "oauth-icon.png"), oauthIcon),
    writeFile(path.join(destination, "icon-512.png"), icon512),
  ]);
  const socialSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630"><rect width="1200" height="630" fill="${c.background}"/><svg x="88" y="72" width="${width * 1.25}" height="90" viewBox="0 0 ${width} 72">${logoSvg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "")}</svg><text x="88" y="308" fill="${c.ink}" font-family="Arial,sans-serif" font-size="62" font-weight="600" letter-spacing="-2">From process interviews</text><text x="88" y="386" fill="${c.ink}" font-family="Arial,sans-serif" font-size="62" font-weight="600" letter-spacing="-2">to clear diagrams.</text><text x="88" y="514" fill="${c.muted}" font-family="Arial,sans-serif" font-size="24">Transcripts · Clarification · Revision history</text><path d="M88 554H1112" stroke="${c.border}" stroke-width="2"/></svg>`;
  await writeFile(path.join(destination, "social-card.png"), await png(socialSvg, 1200, 630, false));
  const icoHeader = Buffer.alloc(22);
  icoHeader.writeUInt16LE(1, 2); icoHeader.writeUInt16LE(1, 4);
  icoHeader[6] = 32; icoHeader[7] = 32;
  icoHeader.writeUInt16LE(1, 10); icoHeader.writeUInt16LE(32, 12);
  icoHeader.writeUInt32LE(faviconPng.length, 14); icoHeader.writeUInt32LE(22, 18);
  await writeFile(path.join(root, "public/favicon.ico"), Buffer.concat([icoHeader, faviconPng]));
  await writeFile(path.join(root, "src/brand-assets.js"),
    `// Generated by scripts/build-brand-assets.js. Canonical mark and typeset wordmark outlines are in branding/artwork.js.\n` +
    `export const brandLogoDataUri = ${JSON.stringify("data:image/svg+xml;base64," + Buffer.from(logoSvg).toString("base64"))};\n` +
    `export const brandFaviconDataUri = ${JSON.stringify("data:image/svg+xml;base64," + Buffer.from(faviconSvg).toString("base64"))};\n` +
    `export const emailLogoBase64 = ${JSON.stringify(emailPng.toString("base64"))};\n` +
    `export const emailLogoDarkBase64 = ${JSON.stringify(emailDarkPng.toString("base64"))};\n` +
    `export const emailLogoWidth = ${emailLogoWidth};\n` +
    `export const emailLogoHeight = ${emailLogoHeight};\n`);
  console.log("Generated SVG logos, PNG email logo, favicon formats, touch icons and offline assets.");
} finally {
  await browser.close();
}
